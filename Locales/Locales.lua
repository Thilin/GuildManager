---@class GMLocale
local Locales = {
    activeLocale = "enUS", -- Padrão: Inglês Norte-Americano (enUS)
    listeners = {},
    strings = {
        enUS = {},
        ptBR = {},
    }
}

--- Tabela proxy L que resolve chaves dinamicamente de acordo com o idioma ativo
local L = setmetatable({}, {
    __index = function(t, key)
        local cur = Locales.activeLocale or "enUS"
        local dict = Locales.strings[cur]
        if dict and dict[key] ~= nil then
            return dict[key]
        end
        -- Fallback para enUS
        local fallback = Locales.strings["enUS"]
        if fallback and fallback[key] ~= nil then
            return fallback[key]
        end
        return tostring(key)
    end,
    __call = function(t, key, ...)
        local str = t[key]
        if select("#", ...) > 0 then
            local ok, formatted = pcall(string.format, str, ...)
            if ok then
                return formatted
            end
        end
        return str
    end
})

GM.L = L
_G.GM_L = L
_G.L = _G.L or L
GM.Locales = Locales

--- Retorna o idioma atualmente ativo ("enUS" ou "ptBR")
---@return string
function GM.GetLocale()
    return Locales.activeLocale or "enUS"
end

--- Define o idioma ativo e notifica listeners imediatamente
---@param lang string @"enUS" ou "ptBR"
---@param silent boolean|nil @se true, não persiste em settings
function GM.SetLocale(lang, silent)
    if lang ~= "enUS" and lang ~= "ptBR" then
        lang = "enUS"
    end

    local changed = (Locales.activeLocale ~= lang)
    Locales.activeLocale = lang

    if not silent and GM.settingsService then
        local settings = GM.settingsService:getSettings()
        if settings and settings.setLanguage and settings:getLanguage() ~= lang then
            GM.settingsService:set("language", lang)
        end
    end

    Locales:notifyListeners(lang)
end

--- Registra um callback para quando o idioma for alterado
---@param cb function(lang: string)
function GM.RegisterLocaleListener(cb)
    if type(cb) == "function" then
        table.insert(Locales.listeners, cb)
    end
end

function Locales:notifyListeners(lang)
    for _, cb in ipairs(self.listeners) do
        pcall(cb, lang)
    end
end

